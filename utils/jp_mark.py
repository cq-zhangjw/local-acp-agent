"""JP auto-mark helper: extract kana-bearing Japanese spans and annotate kanji.

Used by POST /api/jp-mark. Kept in utils/ so the endpoint stays thin and the
MeCab engine is loaded lazily (single process-wide init via the module object).

Safety contract:
- Only spans that contain at least one kana character are treated as Japanese.
  Chinese-only segments never match (ipadic would mis-annotate them).
- Non-Japanese parts are html.escape()d; Japanese parts are generated by the
  deterministic MeCab engine (only <ruby>/<rt> structure), so the joined HTML
  is safe for the frontend to v-html after its own DOMPurify pass.
"""

from __future__ import annotations

import html as html_mod
import importlib.util
import logging
import os
import re
from pathlib import Path

logger = logging.getLogger(__name__)

# Trigger characters: kana only (hiragana/katakana). Punctuation like 。、
# shares code points with Chinese and must NOT trigger a segment.
_KANA_RE = re.compile(
    r"[\u3040-\u30ff\u30a0\u3099-\u309c\u31f0-\u31ff]"
)
# Characters that can extend a segment once triggered: kana, long-vowel,
# Japanese-only punctuation, and CJK ideographs.
_SEG_CHAR_RE = re.compile(
    r"[\u3040-\u30ff\u30fc\u3001\u3002\u300c\u300d\u30fb\u30a0\u3099-\u309c\u31f0-\u31ff\u4e00-\u9fff]"
)

_JP_ASSISTANT_ENTRY = (
    Path(__file__).resolve().parent.parent
    / ".deepagents"
    / "tools"
    / "mcp_servers"
    / "jp_assistant"
    / "jp_assistant_mcp_server.py"
)

_jp_mark_ruby = None  # None=not loaded yet, False=load failed


def _load_jp_mark_ruby():
    global _jp_mark_ruby
    if _jp_mark_ruby is not None:
        return _jp_mark_ruby
    try:
        spec = importlib.util.spec_from_file_location("jp_assistant_mod", _JP_ASSISTANT_ENTRY)
        if spec is None or spec.loader is None:
            raise RuntimeError("jp_assistant entry not importable")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        _jp_mark_ruby = mod.jp_mark_ruby
    except Exception as exc:  # noqa: BLE001 - degrade gracefully
        logger.warning("jp_assistant unavailable, jp auto-mark disabled: %s", exc)
        _jp_mark_ruby = False
    return _jp_mark_ruby


def _extract_jp_spans(text: str) -> list[tuple[int, int]]:
    """Return (start, end) spans of kana-bearing Japanese segments.

    Spans are extended to adjacent kanji, but rejected if the kana ratio is
    too low (i.e. the span is mostly Chinese characters that happen to be
    adjacent to a stray kana).
    """
    spans: list[tuple[int, int]] = []
    n = len(text)
    i = 0
    while i < n:
        if _KANA_RE.match(text[i]):
            s = i
            while s > 0 and _SEG_CHAR_RE.match(text[s - 1]):
                s -= 1
            e = i + 1
            while e < n and _SEG_CHAR_RE.match(text[e]):
                e += 1
            # Reject spans that are mostly CJK (Chinese text with a stray kana).
            # Require at least ~20% kana density to consider it Japanese.
            seg = text[s:e]
            kana_count = len(_KANA_RE.findall(seg))
            if len(seg) > 0 and kana_count / len(seg) >= 0.15:
                spans.append((s, e))
            i = e
        else:
            i += 1
    return spans


def jp_mark_text(text: str) -> dict:
    """Return {has_jp, html} where html is the safe annotated version of text."""
    text = text or ""
    fn = _load_jp_mark_ruby()
    if not fn:
        return {"has_jp": False, "html": html_mod.escape(text)}

    spans = _extract_jp_spans(text)
    if not spans:
        return {"has_jp": False, "html": html_mod.escape(text)}

    out: list[str] = []
    prev = 0
    for s, e in spans:
        # Non-Japanese parts: keep as-is (markdown-it on the frontend will render
        # markdown like **bold**, lists, etc.). Only Japanese spans get ruby HTML.
        out.append(text[prev:s])
        segment = text[s:e]
        marked = fn(segment)
        if isinstance(marked, str) and marked.startswith("Error:"):
            out.append(html_mod.escape(segment))
        else:
            out.append(str(marked))
        prev = e
    out.append(text[prev:])
    return {"has_jp": True, "html": "".join(out)}
